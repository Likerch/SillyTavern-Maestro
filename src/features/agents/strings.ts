function expand(prefix: string, table: Record<string, [string, string]>, secondKey: string): Record<string, string> {
    const out: Record<string, string> = {};
    for (const [id, [name, hint]] of Object.entries(table)) {
        out[`${prefix}.${id}`] = name;
        out[`${prefix}.${id}.${secondKey}`] = hint;
    }
    return out;
}

function expandTemplates(table: Record<string, [string, string]>): Record<string, string> {
    const out: Record<string, string> = {};
    for (const [id, [name, desc]] of Object.entries(table)) {
        out[`m44.tpl.${id}.name`] = name;
        out[`m44.tpl.${id}.desc`] = desc;
    }
    return out;
}

